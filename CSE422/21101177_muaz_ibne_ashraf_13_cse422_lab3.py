import math
import random as rnd

def strength(x):
    return math.log2(x + 1) + x / 10

def utility(max_v, min_v):
    i = rnd.randint(0, 1)
    rnd_comp = rnd.randint(1, 10)
    return (strength(max_v) - strength(min_v) + ((-1) ** i) * rnd_comp) / 10

def minimax(node, dpth, alph, beta, max_plr):
    if dpth == 0 or node.get("terminal", False):
        return node["score"]

    if max_plr:
        max_ev = -float('inf')
        for i in node["next"]:
            ev = minimax(i, dpth - 1, alph, beta, False)
            max_ev = max(max_ev, ev)
            alph = max(alph, ev)
            if beta <= alph:
                break
        return max_ev
    else:
        min_ev = float('inf')
        for i in node["next"]:
            ev = minimax(i, dpth - 1, alph, beta, True)
            min_ev = min(min_ev, ev)
            beta = min(beta, ev)
            if beta <= alph:
                break
        return min_ev

# Problem 1

def chess_masters(st_plr, max_v, min_v):
    rslts = {"Carlsen": 0, "Caruana": 0, "Draw": 0}

    for game in range(4):
        max_plr = (game % 2 == 0) if st_plr == 0 else (game % 2 != 0)
        g_max = max_v if max_plr else min_v
        g_min = min_v if max_plr else max_v
        tree = {"score": utility(g_max, g_min), "terminal": True}

        rslt = minimax(tree, 5, -float('inf'), float('inf'), max_plr)

        if rslt > 0:
            winner = "Carlsen" if max_plr else "Caruana"
        elif rslt < 0:
            winner = "Caruana" if max_plr else "Carlsen"
        else:
            winner = "Draw"

        rslts[winner] += 1
        print(f"Game {game + 1} Winner: {winner} (Utility value: {rslt:.2f})")

    print("\nOverall results:")
    print(f"Carlsen Wins: {rslts['Carlsen']}")
    print(f"Caruana Wins: {rslts['Caruana']}")
    print(f"Draws: {rslts['Draw']}")

    ovr_winner = max(rslts, key=rslts.get)
    if rslts["Carlsen"] == rslts["Caruana"]:
        ovr_winner = "Draw"

    print(f"Overall Winner: {ovr_winner}")

chess_masters(0, 9, 8)

