def chess_noobs_with_magic(st_plr, cost, max_v, min_v):
    tree = {"score": utility(max_v, min_v), "terminal": True}
    b_scr = minimax(tree, 3, -float('inf'), float('inf'), st_plr == 0)
    m_scr = max(max_v, min_v) - cost

    print(f"Minimax value without Mind Control: {b_scr:.2f}")
    print(f"Minimax value with Mind Control: {m_scr:.2f}")
    print(f"Minimax value with Mind Control after incurring the cost: {m_scr - cost:.2f}")

    if b_scr < m_scr - cost:
        print("Light should use Mind Control.")
    else:
        print("Light should NOT use Mind Control.")

chess_noobs_with_magic(0, 0.5, 10, 8)