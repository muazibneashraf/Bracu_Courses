import numpy as np
import random as rnd

def generate_population(size):
    population = []
    for _ in range(size):
        s_loss = f"{rnd.randint(1, 99):02}"
        t_profit = f"{rnd.randint(1, 99):02}"
        trd_size = f"{rnd.randint(1, 99):02}"
        population.append(s_loss + t_profit + trd_size)
    return population

def calculate_fitness(chrmsm, p_chngs):
    s_loss = int(chrmsm[:2]) / 100
    t_profit = int(chrmsm[2:4]) / 100
    trd_size = int(chrmsm[4:]) / 100

    initial_cap = 1000
    for p_chng in p_chngs:
        trd_amount = initial_cap * trd_size
        prof_loss = trd_amount * (p_chng / 100)

        if prof_loss < -trd_amount * s_loss:
            prof_loss = -trd_amount * s_loss
        elif prof_loss > trd_amount * t_profit:
            prof_loss = trd_amount * t_profit

        initial_cap += prof_loss

    return initial_cap - 1000

def selection(population, fitness_scrs):
    return rnd.choices(population, weights=fitness_scrs, k=2)

def crossover(prnt1, prnt2):
    point = rnd.randint(1, 5)
    return prnt1[:point] + prnt2[point:], prnt2[:point] + prnt1[point:]

def mutation(chrmsm):
    index = rnd.randint(0, 5)
    new_gene = f"{rnd.randint(1, 99):02}"[rnd.randint(0, 1)]
    return chrmsm[:index] + new_gene + chrmsm[index+1:]

def genetic_algorithm(gen=10, pop_size=4, p_chngs=None):
    population = generate_population(pop_size)

    for _ in range(gen):
        fitness_scrs = [calculate_fitness(chromo, p_chngs) for chromo in population]
        new_pop = []

        for _ in range(pop_size // 2):
            prnt1, prnt2 = selection(population, fitness_scrs)
            offsprng1, offsprng2 = crossover(prnt1, prnt2)
            new_pop.extend([mutation(offsprng1), mutation(offsprng2)])

        population = new_pop

    best_chrmsm = max(population, key=lambda chromo: calculate_fitness(chromo, p_chngs))
    return best_chrmsm, calculate_fitness(best_chrmsm, p_chngs)

p_chngs = [-1.2, 3.4, -0.8, 2.1, -2.5, 1.7, -0.3, 5.8, -1.1, 3.5]
best_strat, final_prof = genetic_algorithm(p_chngs=p_chngs)
print(f"Best Strategy: {best_strat}, Final Profit: {final_prof}")

