def two_point_crossover(prnt1, prnt2):
    point1, point2 = sorted(rnd.sample(range(1, 5), 2))
    chld1 = prnt1[:point1] + prnt2[point1:point2] + prnt1[point2:]
    chld2 = prnt2[:point1] + prnt1[point1:point2] + prnt2[point2:]
    return chld1, chld2, point1, point2

